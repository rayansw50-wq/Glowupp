-- شغّلي هذا الملف في Supabase: SQL Editor > New query > Run
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  address text not null,
  items jsonb not null,
  total numeric(10,2) not null,
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
-- يسمح للزوار بإرسال طلب جديد فقط. لا تسمحي بقراءة الطلبات من الموقع العام.
create policy "Visitors can submit orders"
on public.orders for insert
to anon, authenticated
with check (
  length(customer_name) between 2 and 100 and
  length(phone) between 5 and 30 and
  length(address) between 3 and 300 and
  total >= 0
);
